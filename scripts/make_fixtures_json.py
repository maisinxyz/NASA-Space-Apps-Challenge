def sse(events: list[dict]) -> str:
    return "".join(f"event: progress\ndata: {json.dumps(e, separators=(',', ':'))}\n\n" for e in events)


def ts(i: int) -> str:
    return f"2026-11-14T18:00:{i * 2:02d}Z"


ERRORS = {
    "INVALID_INPUT": ("lat must be between -90 and 90.", "Check the coordinates and try again.", False),
    "UNSUPPORTED_FILE": ("This file is not a JPG, PNG, or WEBP image.", "Upload a photo in one of those formats.", False),
    "FILE_TOO_LARGE": ("This image is larger than the upload limit.", "Resize the photo and try again.", False),
    "TERRAIN_COVERAGE_MISSING": ("No open elevation data found for this location.", "Try a site in southern BC or use a curated site.", False),
    "DATA_SOURCE_UNAVAILABLE": ("The elevation service is not responding.", "Try again in a minute or use a curated site.", True),
    "WEATHER_UNAVAILABLE": ("Weather data is unavailable and nothing is cached for this location.", "Try again later or use a curated site.", True),
    "SIMULATION_TIMEOUT": ("The simulation took too long.", "Lower the grid resolution and run it again.", True),
    "NOT_FOUND": ("No item with this ID.", "Check the link or go back to the site list.", False),
    "INTERNAL": ("Something went wrong on our side.", "Try again. If it keeps happening, tell the team.", True),
}


def err(code: str) -> dict:
    msg, hint, retry = ERRORS[code]
    return {"error": {"code": code, "message": msg, "hint": hint, "retryable": retry}}


def scans() -> None:
    ok = []
    for i, (stage, pct, msg) in enumerate(STAGES):
        e = {"scan_id": "scan_mock_001", "stage": stage, "pct": pct, "message": msg, "ts": ts(i)}
        if stage == "ready":
            e["terrain_id"] = HILLS
        ok.append(e)
    (FIX / "scans").mkdir(parents=True, exist_ok=True)
    (FIX / "scans" / "sse_success.txt").write_text(sse(ok))

    fail = [
        {"scan_id": "scan_mock_fail", "stage": s, "pct": p, "message": m, "ts": ts(i)}
        for i, (s, p, m) in enumerate(STAGES[:4])
    ]
    fail.append(
        {
            "scan_id": "scan_mock_fail",
            "stage": "failed",
            "pct": 25,
            "message": "No open elevation data found for this location.",
            "ts": ts(4),
            "error": err("TERRAIN_COVERAGE_MISSING")["error"],
        }
    )
    (FIX / "scans" / "sse_fail_coverage.txt").write_text(sse(fail))

    write("scans/scan_created.json", {"scan_id": "scan_mock_001"})
    write("scans/scan_status.json", {"status": "done", "stage": "ready", "pct": 100, "terrain_id": HILLS})
    write(
        "scans/scan_status_failed.json",
        {"status": "failed", "stage": "failed", "pct": 25, "error": err("TERRAIN_COVERAGE_MISSING")["error"]},
    )


# ---------------------------------------------------------------- main
def main() -> None:
    pkgs = {make().id: json.loads((FIX / "terrain" / make().id / "terrain.json").read_text()) for make in T.ALL_TERRAINS}
    hills = T.make_hills()

    write("sites.json", sites(pkgs[HILLS]))
    write(f"storms/{HILLS}.json", storms())
    write("crops.json", crops())
    write(f"rotations/{HILLS}.json", rotations())

    all_metrics, peaks = {}, {}
    for rid in S.ROTATIONS:
        all_metrics[rid], peaks[rid] = metrics(rid, hills.cover)
    write(f"simulations/{SIM}/status.json", status(all_metrics))
    write(f"simulations/{SIM}/evidence.json", evidence(all_metrics))
    for key, stats in diff_stats(peaks, hills.cover).items():
        write(f"simulations/{SIM}/diff/{key}.json", stats)

    for tid, pkg in pkgs.items():
        write(f"terrain/{tid}/layers.json", layer_catalog(tid))
        write(f"terrain/{tid}/provenance.json", provenance(pkg))
        write(f"terrain/{tid}/insights.json", terrain_insights() if tid == HILLS else [])

    write("weather/summary.json", weather_summary())
    scans()
    for code in ERRORS:
        write(f"errors/{code}.json", err(code))

    write(
        "rotations/validate_result.json",
        {
            "valid": True,
            "warnings": [
                {"code": "same_family_consecutive", "message": "Silage corn and winter wheat are both Poaceae in consecutive years.", "year": 2}
            ],
        },
    )
    print("JSON fixtures written:")
    for rid, m in all_metrics.items():
        print(f"  {rid}: runoff {m['runoff_volume_m3']} m3, ponded {m['ponded_area_ha']} ha, erosion {m['erosion_index_mean']}, bare {m['bare_days_per_year']} d")


if __name__ == "__main__":
    main()
