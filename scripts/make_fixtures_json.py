    depth = f.depth_mm().astype(np.float64)
    cell_m2 = T.CELL_SIZE_M**2
    vol_by_frame = depth.sum(axis=(1, 2)) / 1000.0 * cell_m2
    peak = depth.max(axis=0)
    risk = load_png(FIX / "simulations" / SIM / "risk" / f"{rid}.png")
    valid = risk != enc.NODATA
    area_m2 = T.SIZE * T.SIZE * cell_m2
