def hyetograph(daily_mm: list[float]) -> list[float]:
    """Spread each day's total over 24 hours with a fixed bell shape (mock profile)."""
    h = np.arange(24)
    shape = np.exp(-((h - 14) ** 2) / (2 * 4.0**2))
    shape /= shape.sum()
    out = []
    for d in daily_mm:
        hourly = np.round(shape * d, 2)
        hourly[14] += round(d - hourly.sum(), 2)  # keep the daily sum exact
        out.extend(float(round(v, 2)) for v in hourly)
    return out


