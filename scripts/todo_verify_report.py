"""List every TODO(verify) in tracked files -> docs/todo-verify.md (backend rotation PRD §18: nothing unverified ships silently)."""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "todo-verify.md"
SKIP = ("docs/todo-verify.md", "apps/web/lib/api/schema.d.ts")  # the report itself; generated copy of openapi.yaml

hits = subprocess.run(["git", "grep", "-n", "-I", "TODO(verify)"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8").stdout.splitlines()
rows = []
for h in hits:
    path, line, text = h.split(":", 2)
    if path.startswith(SKIP):
        continue
    rows.append(f"| `{path}:{line}` | {text.strip().replace('|', '/')[:160]} |")
OUT.write_text(
    "# TODO(verify) report\n\nGenerated by `python scripts/todo_verify_report.py`. Do not edit by hand.\n\n"
    f"{len(rows)} open items.\n\n| Where | Line |\n| --- | --- |\n" + "\n".join(rows) + "\n",
    encoding="utf-8", newline="\n",
)
print(f"{len(rows)} TODO(verify) items -> {OUT.relative_to(ROOT)}")
