def request_hash(req: dict) -> str:
    """Same bytes as app.twin.types.request_hash: sorted keys, UTF-8, compact JSON."""
    blob = json.dumps(req, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def num(value: float, unit: str, basis: str = "assumed", confidence: str = "low", ranged: bool = False) -> dict:
    out = {"value": value, "unit": unit, "basis": basis, "confidence": confidence}
    if ranged:
        out["p10"] = value
        out["p50"] = value
        out["p90"] = value
    return out


def series(metric: str, unit: str, basis: str, review: bool, years: range | tuple, value: float, absolute: bool = False) -> dict:
    points = []
    for year in years:
        point = {"year": year, "p50": value}
        if absolute or year >= 1:
            point["p10"] = value
            point["p90"] = value
        points.append(point)
    return {
        "metric": metric,
        "unit": unit,
        "basis": basis,
        "confidence": "low",
        "needs_local_review": review,
        "points": points,
    }


